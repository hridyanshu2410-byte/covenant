"""Write fig-repairs.html: the 15 source-repaired programs of Section 7 ("From report to clean run"), each shown as
it renders (a frame of the unmodified program on lavapipe, captured with cap.py), with the timing diagnostics of
the original run attributed to their causes (repairs.json, from the per-case summaries of the repair experiment,
conservative capture) and the result after the source patch.
Run: python3 build_repairs.py && FIGOUT=.. NODE_PATH=/opt/node-tools/node_modules node render.js fig-repairs"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
R = json.loads((HERE / 'repairs.json').read_text())

CAUSES = {  # cause -> (colour, plain description)
    'VKMARK-PSR': ('#5b8fc9', 'present semaphore signalled again while a present may wait on it'),
    'VKMARK-ACQ': ('#8fb9e3', 'acquire semaphore reused while its waiting submission may be pending'),
    'VKMARK-UBO': ('#d0583f', 'host rewrites the uniform buffer a frame in flight reads'),
    'VKMARK-CLR': ('#9a79c2', 'clear barrier does not chain to the acquire wait'),
    'VKMARK-DEPTH': ('#e3a33b', 'shared depth image ordered for colour only'),
    'GST-WAIT': ('#3f9b8f', 'acquire wait at BOTTOM_OF_PIPE blocks nothing'),
    'GST-IA': ('#a3cfc6', 'sampled image made visible to input-attachment reads'),
    'IMGUI-PRE': ('#7d8a99', 'swapchain images transitioned before they are acquired'),
    'SDL-1': ('#b8323a', 'host rewrites vertex buffers frames in flight still read'),
}
HOSTW = {'VKMARK-UBO', 'SDL-1'}  # host-write races, which validation does not track


def timing(p):  # timing diagnostics of the original run (the attributed ones; one structure diagnostic excluded)
    return sum(R[p]['causes'].values())


def bar(p, h=5):
    tot = timing(p)
    segs = ''.join(f'<span style="flex:{n};background:{CAUSES[c][0]}"></span>'
                   for c, n in sorted(R[p]['causes'].items(), key=lambda kv: list(CAUSES).index(kv[0])))
    return f'<div class="cb" style="height:{h}px">{segs}</div>', tot


def tile(p, label, img):
    b, tot = bar(p)
    assert R[p]['after'] == 0
    return (f'<div class="tile"><img src="img/{img}.jpg"><div class="tl">{label}</div>'
            f'<div class="tc">{b}<div class="num"><span class="bad">{tot:,}</span> → <span class="ok">0</span></div></div></div>')


VK = ['shading', 'texture', 'vertex', 'desktop', 'clear', 'cube', 'effect2d']
vk_total = sum(timing('vkmark_' + v) for v in VK)
gst = ['gst_sink', 'gst_colorconvert', 'gst_overlay', 'gst_viewconvert', 'gst_shaderspv']
gst_total = sum(timing(p) for p in gst)
im_total = timing('imgui_glfw') + timing('imgui_sdl2')
sdl_total = timing('sdl_testsprite')
assert (vk_total, gst_total, im_total, sdl_total) == (1124, 495, 40, 166), (vk_total, gst_total, im_total, sdl_total)


def card(img, title, sub, progs, total, patch, causes):
    rows = ''.join(f'<div class="pr"><span class="pn">{n}</span>{bar(p, 4)[0]}<span class="pc">{timing(p)}</span></div>'
                   for n, p in progs)
    cs = ''.join(f'<span class="sw" style="background:{CAUSES[c][0]}"></span>' for c in causes)
    return f'''<div class="card"><div class="cimg"><img src="img/{img}.jpg"></div><div class="ctx">
<div class="ct">{title}</div><div class="cs">{sub}</div>{rows}
<div class="cn"><span class="bad">{total:,}</span> → <span class="ok">0</span> <span class="dim">diagnostics</span></div>
<div class="cp">{cs} {patch}</div></div></div>'''


legend = ''.join(f'<div class="lg"><span class="sw" style="background:{c}"></span><b>{k}</b> {d}{" <i>(host write)</i>" if k in HOSTW else ""}</div>'
                 for k, (c, d) in CAUSES.items())

