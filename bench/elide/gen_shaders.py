"""Compile shaders/*.{comp,vert,frag} with glslangValidator and embed the
SPIR-V in shaders_spv.h (checked in, so building the workloads elsewhere,
e.g. on a GPU machine, needs no shader compiler).

    python3 gen_shaders.py
"""
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent


def main():
    out = ["// Generated by gen_shaders.py from shaders/; do not edit.", "#pragma once", "#include <cstdint>", ""]
    with tempfile.TemporaryDirectory() as tmp:
        for src in sorted((HERE / "shaders").iterdir()):
            if src.suffix not in (".comp", ".vert", ".frag"):
                continue
            spv = Path(tmp) / (src.name + ".spv")
            subprocess.run(["glslangValidator", "--quiet", "--target-env", "vulkan1.3", "-V", str(src), "-o", str(spv)],
                           check=True)
            data = spv.read_bytes()
            words = [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]
            ident = src.name.replace(".", "_")
            out.append(f"static const uint32_t {ident}[] = {{")
            for i in range(0, len(words), 8):
                out.append("  " + ", ".join(f"0x{w:08x}u" for w in words[i:i + 8]) + ",")
            out.append("};")
            out.append("")
    (HERE / "shaders_spv.h").write_text("\n".join(out))
    print("wrote", HERE / "shaders_spv.h")


if __name__ == "__main__":
    sys.exit(main())
