// Distilled from ford442/brain_viz #341 (fix PR #350): the render
// uniforms are filled from JavaScript into a Float32Array with hand-written
// float offsets (uniforms.js), while the WGSL struct lives in mesh.js /
// fiber.js. The struct had gained `dopamineTrails: f32` at float 36, and
// `slicePlane: vec4<f32>` after it is aligned to 16 bytes, i.e. float 40.
// The stale offsets still wrote the slice plane at 36 and sparkle, growth,
// aberration, grain at 40-43: every field from the clip plane on was uploaded
// four floats low and dopamineTrails was never written ("slicePlane is a
// vec4 and cannot follow an f32 at float 36 -- WGSL pads it to 40"). The
// fix generates the WGSL struct and the JS offsets from one layout table.
// (WebGPU upstream; Float32Array + writeBuffer becomes a float array copied
// into a mapped uniform buffer.)
#include "../../common/app.hpp"
#include <cmath>
using namespace bench;

// uniforms.js
#ifdef FIXED
// RENDER_UNIFORM_OFFSETS, generated by uniform-layout.js
static const int OFFSET_COLOR = 35, OFFSET_DOPAMINE = 36, OFFSET_SLICE = 40, OFFSET_SPARKLE = 44,
                 OFFSET_GROWTH = 45, OFFSET_ABERRATION = 46, OFFSET_GRAIN = 47;
#else
static const int OFFSET_COLOR = 35, OFFSET_SLICE = 36, OFFSET_SPARKLE = 40,
                 OFFSET_GROWTH = 41, OFFSET_ABERRATION = 42, OFFSET_GRAIN = 43;
#endif
static const int OFFSET_VIEWPROJ = 0, OFFSET_MODEL = 16, OFFSET_TIME = 32, OFFSET_PULSE = 33, OFFSET_GLOW = 34;
static const int UNIFORM_FLOATS = 48;

struct Params { float time, pulse, glow, colorShift, dopamineTrails, slice[4], sparkle, growth, aberration, grain; };

static void write_uniforms(float* u, const Params& p) {
  for (int i = 0; i < 4; i++) u[OFFSET_VIEWPROJ + i * 5] = u[OFFSET_MODEL + i * 5] = 1.0f;
  u[OFFSET_VIEWPROJ + 10] = 0.5f; u[OFFSET_VIEWPROJ + 14] = 0.5f;
  u[OFFSET_TIME] = p.time; u[OFFSET_PULSE] = p.pulse; u[OFFSET_GLOW] = p.glow;
  u[OFFSET_COLOR] = p.colorShift;
#ifdef FIXED
  u[OFFSET_DOPAMINE] = p.dopamineTrails;
#endif
  for (int i = 0; i < 4; i++) u[OFFSET_SLICE + i] = p.slice[i];
  u[OFFSET_SPARKLE] = p.sparkle; u[OFFSET_GROWTH] = p.growth;
  u[OFFSET_ABERRATION] = p.aberration; u[OFFSET_GRAIN] = p.grain;
}

int main(int argc, char** argv) {
  App a = make_app(argc, argv);
  auto sh = load_shader(a, "shaders.spv");
  const int FRAMES_IN_FLIGHT = 2;
  std::vector<Buffer> ubo;
  auto setl = make_set_layout(a, {{0, VK_DESCRIPTOR_TYPE_UNIFORM_BUFFER, VK_SHADER_STAGE_VERTEX_BIT | VK_SHADER_STAGE_FRAGMENT_BIT}});
  std::vector<VkDescriptorSet> sets;
  for (int i = 0; i < FRAMES_IN_FLIGHT; i++) {
    ubo.push_back(make_buffer(a, UNIFORM_FLOATS * 4, VK_BUFFER_USAGE_UNIFORM_BUFFER_BIT, true, "render_uniforms[" + std::to_string(i) + "]"));
    sets.push_back(alloc_set(a, setl, "render_bind_group[" + std::to_string(i) + "]"));
    write_buffer(a, sets[i], 0, VK_DESCRIPTOR_TYPE_UNIFORM_BUFFER, ubo[i]);
  }
  // brain mesh stand-in: one triangle
  Buffer vb = make_buffer(a, 9 * 4, VK_BUFFER_USAGE_VERTEX_BUFFER_BIT, true, "brain_mesh");
  float tri[9] = {0, -0.6f, 0, 0.6f, 0.6f, 0, -0.6f, 0.6f, 0};
  memcpy(vb.map, tri, sizeof tri);
  GfxDesc gd; gd.vs = gd.fs = sh; gd.vs_entry = "vsMesh"; gd.fs_entry = "fsMesh"; gd.sets = {setl};
  gd.colors = {a.swap_format}; gd.vertex_stride = 12; gd.attributes = {{0, 0, VK_FORMAT_R32G32B32_SFLOAT, 0}};
  Pipeline mesh = make_graphics(a, gd, "brain_mesh");

  run_frames(a, frames_from_env(3), FRAMES_IN_FLIGHT, [&](VkCommandBuffer c, uint32_t idx, int f) {
    int k = f % FRAMES_IN_FLIGHT;
    begin_rendering(a, c, {a.swap_views[idx]});
    vkCmdBindPipeline(c, VK_PIPELINE_BIND_POINT_GRAPHICS, mesh.pipe);
    vkCmdBindDescriptorSets(c, VK_PIPELINE_BIND_POINT_GRAPHICS, mesh.layout, 0, 1, &sets[k], 0, nullptr);
    VkDeviceSize off = 0;
    vkCmdBindVertexBuffers(c, 0, 1, &vb.buf, &off);
    vkCmdDraw(c, 3, 1, 0, 0);
    vkCmdEndRendering(c);
  }, [&](int f) {
    // updateUniforms(): device.queue.writeBuffer(uniformBuffer, 0, uniformData)
    float data[UNIFORM_FLOATS] = {};
    Params p{f * 0.016f, 2.0f, 0.5f, 0.25f, 0.8f, {1.0f, 0.0f, 0.0f, 0.2f}, 0.6f, 0.3f, 0.1f, 0.05f};
    write_uniforms(data, p);
    memcpy(ubo[f % FRAMES_IN_FLIGHT].map, data, sizeof data);
  });
}
