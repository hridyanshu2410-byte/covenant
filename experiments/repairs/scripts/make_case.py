#!/usr/bin/env python3
"""Write <case dir>/summary.md and <case dir>/data/*.json for one repair case from the run outputs.
usage: make_case.py <case dir> <case id> <progs comma-separated> <label>=<run root> ...
The first label is the original program; every later label is a patched variant. Each diagnostic is
attributed to a cause by the written rules in RULES (code + resource/message), so 'remaining' lists
are mechanical. Verdict per variant and program (conservative capture, the proved configuration):
clean = no diagnostic attributed to the case's cause and no diagnostic code absent from the original."""
import json, os, re, sys, collections

RULES = [  # (project prefix, code, message regex, cause)
    ('vkmark', 'timing.present-semaphore-reuse', r'', 'VKMARK-PSR'),
    ('vkmark', 'timing.acquire-semaphore-in-use', r'', 'VKMARK-ACQ'),
    ('vkmark', 'timing.cross-queue-race', r"'host'", 'VKMARK-UBO'),
    ('vkmark', 'timing.barrier-scope', r'depth', 'VKMARK-DEPTH'),
    ('vkmark', 'timing.acquire-first-use', r'swapchain', 'VKMARK-CLR'),
    ('vkmark', 'timing.wait-stage-scope', r'swapchain', 'VKMARK-CLR'),
    ('gst', 'timing.cross-queue-race', r'swapchain', 'GST-WAIT'),
    ('gst', 'timing.acquire-first-use', r'swapchain', 'GST-WAIT'),
    ('gst', 'timing.barrier-scope', r'INPUT_ATTACHMENT_READ', 'GST-IA'),
    ('imgui', 'timing.acquire-first-use', r'swapchain', 'IMGUI-PRE'),
    ('sdl', 'timing.cross-queue-race', r"'host'", 'SDL-1'),
]

def cause(prog, f):
    proj = prog.split('_')[0]
    for p, code, rx, c in RULES:
        if proj == p and f['code'] == code and re.search(rx, f['message'] + ' ' + ' '.join(f.get('notes', []))):
            return c
    return 'UNATTRIBUTED'

def load(root, prog):
    s = {}
    for m in ('conservative', 'observed'):
        d = os.path.join(root, prog, m)
        try:
            cj = json.load(open(os.path.join(d, 'check.json')))
        except Exception:
            s[m] = None; continue
        f = cj['findings']; st = cj.get('stats', {})
        g = open(os.path.join(d, 'groups.txt'), errors='replace').read().splitlines()
        mm = re.search(r'-> (\d+) groups', g[0]) if g else None
        s[m] = {'diagnostics': len(f), 'groups': int(mm.group(1)) if mm else 0,
                'by_code': dict(sorted(collections.Counter(x['code'] for x in f).items())),
                'by_cause': dict(sorted(collections.Counter(cause(prog, x) for x in f).items())),
                'by_code_cause': dict(sorted(collections.Counter(f"{x['code']} -> {cause(prog, x)}" for x in f).items())),
                'warnings': st.get('warnings'), 'unimplemented': st.get('unimplemented') or [],
                # P1/P3 capture problems and unmodelled commands are reported as timing.unmodelled*
                'unmodelled': sum(1 for x in f if x['code'].startswith('timing.unmodelled')),
                'presents': st.get('presents'), 'submits': st.get('submits'),
                'groups_headline': g[0] if g else '',
                'example': {x['code']: x['message'] + ' | at ' + x.get('where', '') for x in reversed(f)}}
    ts = os.path.join(root, prog, 'trace_status.txt')
    s['trace'] = open(ts).read().strip() if os.path.exists(ts) else None
    v = os.path.join(root, 'sv_' + prog, 'vvl.txt')
    if os.path.exists(v):
        ids = re.findall(r'\[ ([A-Za-z0-9_-]+) \]', open(v, errors='replace').read())
        st = open(os.path.join(root, 'sv_' + prog, 'status.txt')).read().strip()
        s['validation'] = {'status': st, 'by_id': dict(sorted(collections.Counter(ids).items()))}
    else:
        s['validation'] = None
    return s

def fmt_codes(d):
    return ', '.join(f'`{k.replace("timing.", "")}` {v}' for k, v in d.items()) or '-'

def main():
    out, case, progs = sys.argv[1], sys.argv[2], sys.argv[3].split(',')
    variants = [a.split('=', 1) for a in sys.argv[4:]]
    os.makedirs(os.path.join(out, 'data'), exist_ok=True)
    L = [f'# {case}: before/after check summaries', '',
         'Generated by `scripts/make_case.py` from the run outputs.',
         'Checker: the checker at `$COVENANT_ROOT` (`covenant_version` in each check.json); each program traced',
         'under the model driver (20 presents) and checked in conservative (proved configuration) and observed',
         'host capture; validation = lavapipe + VVL with synchronization validation (`sv.sh`), same',
         'program and present count. Premises: capture warnings (P1 host writes trapped / P3 one recording thread)',
         'and unmodelled commands are reported by the checker itself (stats.warnings / stats.unimplemented and',
         '`timing.unmodelled*` findings, see covenant/host_trace.py note_unsupported).', '']
    verdicts = {}
    allj = {}
    for prog in progs:
        rows = []; base = None
        L += [f'## {prog}', '',
              '| variant | cons. diagnostics | cons. groups | obs. diagnostics | obs. groups | per code (conservative) | model warnings / `timing.unmodelled*` (P1, P3) | unimplemented commands | validation (VVL) |',
              '| --- | ---: | ---: | ---: | ---: | --- | --- | --- | --- |']
        for i, (lab, root) in enumerate(variants):
            s = load(root, prog); allj[f'{prog}/{lab}'] = s
            c, o = s['conservative'], s['observed']
            if c is None:
                L.append(f'| {lab} | not run | | | | | | | |'); continue
            v = s['validation']
            vs = 'not run' if v is None else (', '.join(f'`{k}` {n}' for k, n in v['by_id'].items()) or 'no message') + ('' if v['status'].startswith('rc=0') else f" ({v['status']})")
            L.append(f"| {lab} | {c['diagnostics']} | {c['groups']} | {o['diagnostics'] if o else '-'} | {o['groups'] if o else '-'} | {fmt_codes(c['by_code'])} | {c['warnings']} / {c['unmodelled']} | {', '.join(c['unimplemented']) or 'none'} | {vs} |")
            if i == 0:
                base = s
        L.append('')
        for i, (lab, root) in enumerate(variants):
            s = allj[f'{prog}/{lab}']; c = s['conservative']
            if c is None: continue
            L.append(f"- **{lab}** attribution (conservative): " + (', '.join(f'{k} {v}' for k, v in c['by_code_cause'].items()) or 'no diagnostic'))
            if i > 0 and base and base['conservative']:
                own = c['by_cause'].get(case, 0) if case in RULE_CAUSES else None
                new = sorted(set(c['by_code']) - set(base['conservative']['by_code']))
                rem = {k: v for k, v in c['by_cause'].items()}
                obs_same = s['observed'] and s['observed']['by_code'] == c['by_code']
                prem = (c['warnings'] in (0, None)) and not c['unimplemented'] and not c['unmodelled']
                verdicts[(prog, lab)] = {'own_remaining': own, 'new_codes': new, 'remaining_by_cause': rem,
                                         'observed_same': bool(obs_same), 'premises_ok': prem,
                                         'clean_for_case': (own == 0 or own is None) and not new,
                                         'fully_clean': c['diagnostics'] == 0}
                L.append(f"  - verdict vs original: diagnostics of this case's cause remaining: {own}; new diagnostic codes: {', '.join(new) or 'none'}; observed capture identical: {'yes' if obs_same else 'no'}; premises (no model warning, no `timing.unmodelled*` P1/P3/command finding, no unimplemented command): {'met' if prem else 'NOT met'}")
        L.append('')
        for lab, _ in variants:
            s = allj[f'{prog}/{lab}']
            if s['trace']:
                L.append(f'  - trace {lab}: `{s["trace"]}`')
        L.append('')
    # examples of every remaining code in patched variants
    L += ['## Example message per remaining diagnostic code (patched variants, conservative)', '']
    seen = set()
    for prog in progs:
        for lab, _ in variants[1:]:
            c = allj[f'{prog}/{lab}']['conservative']
            if not c: continue
            for code, ex in c['example'].items():
                if (lab, code) in seen: continue
                seen.add((lab, code))
                L.append(f'- {lab} / {prog} / `{code}`: {ex}')
    open(os.path.join(out, 'summary.md'), 'w').write('\n'.join(L) + '\n')
    json.dump({k: {kk: (vv if kk not in ('conservative', 'observed') or vv is None else {x: y for x, y in vv.items() if x != 'example'}) for kk, vv in v.items()} for k, v in allj.items()},
              open(os.path.join(out, 'data', 'runs.json'), 'w'), indent=1)
    json.dump({f'{p}/{l}': v for (p, l), v in verdicts.items()}, open(os.path.join(out, 'data', 'verdicts.json'), 'w'), indent=1)
    print(json.dumps({f'{p}/{l}': (v['clean_for_case'], v['fully_clean'], v['own_remaining'], v['new_codes']) for (p, l), v in verdicts.items()}))

RULE_CAUSES = {r[3] for r in RULES}
main()
