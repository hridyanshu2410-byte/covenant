#!/usr/bin/env python3
"""Generate covvk_gen.inc from the installed Vulkan headers.

It holds (1) enum/flag -> name tables used by the trace writer, (2) a stub for
every Vulkan command that covvk.cpp does not implement by hand (the stub logs a
warning record and returns a harmless value), and (3) the name -> function
table that vkGetInstanceProcAddr / vkGetDeviceProcAddr consult.

usage: gen.py <vulkan_core.h> <covvk.cpp> <enums.inc> <stubs.inc>
"""
import re
import sys

core_h, impl_cpp, enums_path, stubs_path = sys.argv[1:5]
src = open(core_h).read()
_impl_src = open(impl_cpp).read()
# vkCmdSet* dynamic state that cannot add memory accesses beyond those the loader
# already assumes (it over-approximates: every bound vertex buffer, every color
# attachment written, depth per vkCmdSetDepth*Enable): recorded with their
# command buffer and no warning. Every other unimplemented vkCmd* -- including
# vkCmdSet* not listed here -- is recorded with a "warning", which the loader
# reports (timing.unmodelled-command) and elide.py pins.
HARMLESS_DYNAMIC_STATE = {"vkCmdSet" + n + sfx for sfx in ("", "EXT", "KHR", "NV") for n in (
    "Viewport", "Scissor", "ViewportWithCount", "ScissorWithCount", "LineWidth", "DepthBias", "DepthBias2",
    "BlendConstants", "DepthBounds", "StencilCompareMask", "StencilWriteMask", "StencilReference", "CullMode",
    "FrontFace", "PrimitiveTopology", "PrimitiveRestartEnable", "DepthBoundsTestEnable", "StencilTestEnable",
    "StencilOp", "RasterizerDiscardEnable", "DepthBiasEnable", "LineStipple", "LineStippleEnable",
    "ViewportWScaling", "ViewportWScalingEnable", "DiscardRectangle", "DiscardRectangleEnable",
    "DiscardRectangleMode", "SampleLocations", "SampleLocationsEnable", "PatchControlPoints", "PolygonMode",
    "TessellationDomainOrigin", "DepthClampEnable", "DepthClampRange", "DepthClipEnable", "AlphaToCoverageEnable",
    "AlphaToOneEnable", "SampleMask", "RasterizationSamples", "RasterizationStream", "ExclusiveScissor",
    "ExclusiveScissorEnable", "ConservativeRasterizationMode", "ExtraPrimitiveOverestimationSize",
    "ProvokingVertexMode", "LineRasterizationMode", "DepthClipNegativeOneToOne", "ViewportSwizzle",
    "CoverageModulationMode", "CoverageModulationTableEnable", "CoverageModulationTable", "CoverageToColorEnable",
    "CoverageToColorLocation", "CoverageReductionMode", "ShadingRateImageEnable", "RepresentativeFragmentTestEnable",
    "DeviceMask", "RayTracingPipelineStackSize", "CheckpointNV", "VertexInput", "ColorWriteEnable",
    "ColorWriteMask", "ColorBlendEnable", "ColorBlendEquation", "ColorBlendAdvanced", "LogicOp",
    "LogicOpEnable", "FragmentShadingRate", "FragmentShadingRateEnum", "ViewportShadingRatePalette",
    "CoarseSampleOrder", "PrimitiveRestartIndex", "ComputeOccupancyPriority", "PerformanceMarkerINTEL",
    "PerformanceStreamMarkerINTEL", "PerformanceOverrideINTEL")}
impl = set(re.findall(r"VKAPI_CALL\s+(vk\w+)\s*\(", _impl_src))
impl |= {"vkDestroy" + n for n in re.findall(r"^COVVK_DESTROY\((\w+),", _impl_src, re.M)}

ENUMS = ["VkFormat", "VkImageLayout", "VkDescriptorType", "VkAttachmentLoadOp",
         "VkAttachmentStoreOp", "VkPipelineBindPoint", "VkPresentModeKHR",
         "VkColorSpaceKHR", "VkIndexType", "VkPrimitiveTopology", "VkObjectType",
         "VkFilter", "VkSamplerAddressMode", "VkSamplerMipmapMode", "VkImageType",
         "VkImageViewType", "VkImageTiling", "VkSharingMode", "VkCompareOp",
         "VkCommandBufferLevel", "VkSubpassContents", "VkPolygonMode",
         "VkCullModeFlagBits", "VkDynamicState", "VkSemaphoreType", "VkVertexInputRate",
         "VkResolveModeFlagBits", "VkBlendFactor", "VkBlendOp"]
FLAGS = ["VkBufferUsageFlagBits", "VkImageUsageFlagBits", "VkShaderStageFlagBits",
         "VkImageAspectFlagBits", "VkMemoryPropertyFlagBits", "VkCommandBufferUsageFlagBits",
         "VkPipelineStageFlagBits2", "VkAccessFlagBits2", "VkSampleCountFlagBits",
         "VkDependencyFlagBits", "VkCommandPoolCreateFlagBits", "VkQueueFlagBits"]


def enum_members(name):
    m = re.search(r"typedef enum %s \{(.*?)\} %s;" % (name, name), src, re.S)
    out, seen = [], set()
    if m:
        for n, v in re.findall(r"^\s*(VK_\w+)\s*=\s*(-?0x[0-9A-Fa-f]+|-?\d+)\s*,?\s*$",
                               m.group(1), re.M):
            if n.endswith("_MAX_ENUM"):
                continue
            iv = int(v, 0)
            if iv not in seen:
                seen.add(iv)
                out.append((n, iv))
    else:   # 64-bit flags are static consts
        for n, v in re.findall(r"static const %s (VK_\w+) = (0x[0-9A-Fa-f]+)ULL;" % name, src):
            iv = int(v, 0)
            if iv not in seen:
                seen.add(iv)
                out.append((n, iv))
    return out


lines = ["// generated by gen.py from %s -- do not edit" % core_h, ""]
for e in ENUMS:
    lines.append("static const char* name_%s(int64_t v) {\n  switch (v) {" % e)
    for n, v in enum_members(e):
        lines.append("    case %d: return \"%s\";" % (v, n))
    lines.append("    default: return nullptr;\n  }\n}")
for f in FLAGS:
    mem = [(n, v) for n, v in enum_members(f) if v and (v & (v - 1)) == 0]
    lines.append("static const FlagName flags_%s[] = {" % f)
    for n, v in mem:
        lines.append("  {0x%xULL, \"%s\"}," % (v, n))
    lines.append("  {0, nullptr}};")

open(enums_path, "w").write("\n".join(lines) + "\n")
lines = ["// generated by gen.py from %s -- do not edit" % core_h, ""]
handles = set(re.findall(r"VK_DEFINE_(?:NON_DISPATCHABLE_)?HANDLE\((\w+)\)", src))

# prototypes (only those under VK_NO_PROTOTYPES guards are declared with VKAPI_ATTR)
protos = re.findall(r"VKAPI_ATTR\s+([\w\s\*]+?)\s+VKAPI_CALL\s+(vk\w+)\s*\((.*?)\);", src, re.S)
names = []
lines.append("")
lines.append('extern "C" {')
for ret, name, params in protos:
    if name in names:
        continue
    names.append(name)
    if name in impl:
        continue
    params = " ".join(params.split())
    plist = [p.strip() for p in params.split(",")] if params != "void" else []
    argnames = [re.match(r"(.*?)(\w+)(\[\d+\])?$", p).group(2) for p in plist]
    base = re.sub(r"(KHR|EXT)$", "", name)
    if base != name and base in impl:
        r = ret.strip()
        call = "%s(%s)" % (base, ", ".join(argnames))
        lines.append("VKAPI_ATTR %s VKAPI_CALL %s(%s) {\n  %s%s;\n}" % (
            r, name, params, "" if r == "void" else "return ", call))
        continue
    if name in HARMLESS_DYNAMIC_STATE and argnames and plist[0].startswith("VkCommandBuffer"):
        body = ["  covvk_record_cmd(\"%s\", (uint64_t)%s);" % (name, argnames[0])]
    elif name.startswith("vkCmd") and argnames and plist[0].startswith("VkCommandBuffer"):
        # recorded with its command buffer, so the loader knows when it is submitted
        body = ["  covvk_unimplemented_cmd(\"%s\", (uint64_t)%s);" % (name, argnames[0])]
    else:
        body = ["  covvk_unimplemented(\"%s\");" % name]
    for p in plist:
        m = re.match(r"(.*?)(\w+)(\[\d+\])?$", p)
        ptype, pname = m.group(1).strip(), m.group(2)
        if ptype == "uint32_t*" and pname.endswith("Count"):
            body.append("  if (%s) *%s = 0;" % (pname, pname))
    if plist and (name.startswith("vkCreate") or name.startswith("vkAllocate")):
        m = re.match(r"(.*?)(\w+)$", plist[-1])
        t = m.group(1).strip()
        if t.endswith("*") and not t.startswith("const") and t[:-1].strip() in handles:
            body.append("  if (%s) *%s = covvk_fake_handle<%s>(\"%s\");"
                        % (m.group(2), m.group(2), t[:-1].strip(),
                           t[:-1].strip()[2:].lower()))
    r = ret.strip()
    if r == "void":
        pass
    elif r == "VkResult":
        body.append("  return VK_SUCCESS;")
    elif r == "PFN_vkVoidFunction":
        body.append("  return nullptr;")
    else:
        body.append("  return (%s)0;" % r)
    lines.append("VKAPI_ATTR %s VKAPI_CALL %s(%s) {\n%s\n}" % (r, name, params, "\n".join(body)))
lines.append("}  // extern C")
lines.append("")
# (4) every VkPhysicalDevice*Features struct of vulkan_core.h that holds only
# VkBool32 members after sType/pNext, with its sType, so vkGetPhysicalDeviceFeatures2
# can report each one as supported (vk.xml next to the header, if present)
import os
import xml.etree.ElementTree as ET
feat = []
xml_path = os.environ.get("VK_XML") or os.path.join(os.path.dirname(core_h), "..", "..", "registry", "vk.xml")
if not os.path.exists(xml_path):
    xml_path = "/usr/share/vulkan/registry/vk.xml"
if os.path.exists(xml_path):
    core_structs = set(re.findall(r"typedef struct (\w+) \{", src))
    for t in ET.parse(xml_path).getroot().iter("type"):
        if t.get("category") != "struct" or "VkPhysicalDeviceFeatures2" not in (t.get("structextends") or ""):
            continue
        name = t.get("name")
        if name not in core_structs:
            continue
        mem = t.findall("member")
        stype = mem[0].get("values") if mem else None
        if not stype or any(m.findtext("type") != "VkBool32" for m in mem[2:]):
            continue
        if any(f[0] == stype for f in feat):
            continue
        feat.append((stype, name))
ft = ["static const struct { VkStructureType st; size_t size; } covvk_feature_structs[] = {"]
for st, name in feat:
    ft.append("  {%s, sizeof(%s)}," % (st, name))
ft.append("  {VK_STRUCTURE_TYPE_MAX_ENUM, 0}};")
with open(enums_path, "a") as f:     # the enums file is included before the entry points
    f.write("\n".join(ft) + "\n")
lines.append("static const ProcEntry covvk_procs[] = {")
for n in sorted(names):
    lines.append("  {\"%s\", (PFN_vkVoidFunction)&%s}," % (n, n))
lines.append("  {nullptr, nullptr}};")
open(stubs_path, "w").write("\n".join(lines) + "\n")
print("gen.py: %d commands, %d hand-written, %d stubs, %d feature structs" %
      (len(names), len(impl & set(names)), len(set(names) - impl), len(feat)))
